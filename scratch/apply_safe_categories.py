# Verify lengths
for k, v in categories_safe.items():
    b_len = len(v.encode('utf-8'))
    if b_len > 11:
        print(f"ERROR: {k} = '{v}' has {b_len} bytes (> 11)!")

import re

with open('src/data/pokemon/pokedex_entries.h', 'r', encoding='utf-8') as f:
    code = f.read()

count = 0
for dex, cat in categories_safe.items():
    pattern = rf'(\[{dex}\]\s*=\s*\{{[^}}]*?\.categoryName\s*=\s*_\(")[^"]*("\))'
    if re.search(pattern, code):
        code = re.sub(pattern, rf'\g<1>{cat}\g<2>', code)
        count += 1
    else:
        print(f"WARN: Category for {dex} not found")

with open('src/data/pokemon/pokedex_entries.h', 'w', encoding='utf-8', newline='\n') as f:
    f.write(code)

print(f"Sucesso! {count}/100 categorias de Pokédex atualizadas com tamanho seguro!")
