import re
import os
import struct

def get_png_plte(path):
    if not os.path.exists(path):
        return None
    with open(path, 'rb') as f:
        data = f.read()
    idx = 8
    while idx < len(data):
        length, ctype = struct.unpack('>I4s', data[idx:idx+8])
        if ctype == b'PLTE':
            plte = data[idx+8:idx+8+length]
            cols = []
            for i in range(0, min(len(plte), 48), 3):
                r, g, b = plte[i], plte[i+1], plte[i+2]
                bgr555 = (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
                cols.append(bgr555)
            while len(cols) < 16:
                cols.append(0)
            return cols[:16]
        idx += 12 + length
    return None

def main():
    pic_to_file = {}
    with open('src/data/object_events/object_event_graphics.h', 'r', encoding='latin-1') as f:
        for line in f:
            m = re.search(r'const u32 (gObjectEventPic_\w+)\[\] = INCBIN_U32\("graphics/object_events/pics/pokemon/(\w+)\.4bpp"\);', line)
            if m:
                pic_to_file[m.group(1)] = m.group(2)

    table_to_pic = {}
    with open('src/data/object_events/object_event_pic_tables.h', 'r', encoding='latin-1') as f:
        content = f.read()
        for m in re.finditer(r'static const struct SpriteFrameImage (sPicTable_\w+)\[\] = \{[^}]*overworld_frame\((gObjectEventPic_\w+)', content):
            table_to_pic[m.group(1)] = m.group(2)

    species_order = []
    species_to_file = {}
    with open('src/data/object_events/object_event_graphics_info_followers.h', 'r', encoding='latin-1') as f:
        for line in f:
            m = re.search(r'\[(SPECIES_\w+)\]\s*=\s*\{.*?(sPicTable_\w+)', line)
            if m:
                sp = m.group(1)
                tbl = m.group(2)
                pic = table_to_pic.get(tbl)
                fn = pic_to_file.get(pic)
                species_order.append(sp)
                species_to_file[sp] = fn

    lines = []
    lines.append("// Auto-generated by tools/gen_ow_palettes.py")
    lines.append("// Real 16-color genuine palettes extracted directly from overworld PNGs")
    lines.append("#ifndef POKEMON_OVERWORLD_PALETTES_H")
    lines.append("#define POKEMON_OVERWORLD_PALETTES_H\n")
    lines.append("#include \"constants/species.h\"\n")

    for sp in species_order:
        fn = species_to_file.get(sp)
        if fn:
            png_path = f"graphics/object_events/pics/pokemon/{fn}.png"
            cols = get_png_plte(png_path)
        else:
            cols = None
        if not cols:
            cols = [0] * 16

        cols_str = ", ".join(f"0x{c:04X}" for c in cols)
        lines.append(f"static const u16 sOverworldPal_{sp}[] = {{{cols_str}}};")

    lines.append("\nconst struct SpritePalette gOverworldPokemonPaletteTable[] = {")
    for sp in species_order:
        lines.append(f"    [{sp}] = {{sOverworldPal_{sp}, {sp}}},")
    lines.append("};\n")
    lines.append("#endif // POKEMON_OVERWORLD_PALETTES_H\n")

    out_path = 'src/data/object_events/pokemon_overworld_palettes.h'
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write("\n".join(lines))
    print(f"Generated {out_path} with {len(species_order)} palettes.")

if __name__ == '__main__':
    main()
